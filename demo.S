/* demo_raw_fp.S */
.global _start

.text
# ==========================================
# 1. エントリーポイント
# ==========================================
_start:
    # スタックポインタ(sp)の初期化
    li sp, 0x80080000
    # フレームポインタ(fp)の初期化 (一番最初の根っこなので0にしておくのが定石)
    li fp, 0

    # 引数の準備: a0 = 10, a1 = 20
    li a0, 10
    li a1, 20

    # calcのアドレスへ飛び、戻り先を ra に保存する
    jal ra, calc

end_loop:
    # 無限ループ。戻り先は不要なので zero に捨てる
    jal zero, end_loop


# ==========================================
# 2. 中間関数 (calc)
# ==========================================

calc:

    # --- プロローグ (fpの構築) ---
    addi sp, sp, -16     # 1. スタックを確保
    sd fp, 0(sp)         # 2. 古いfpを退避（ここは絶対にsp基準！）
    # 【ここで fp レジスタを「今の関数の天井」に更新する！】
    addi fp, sp, 16      # 3. fpレジスタが 0x8000 に書き換わる
    # 4. fpが新しくなったので、ここからは fp 基準で書ける！
    sd ra, -8(fp)        # 0x8000 - 8 = 0x7FF8。見事、正しい場所に保存！

    # --- 関数本体 ---
    # add_funcへ飛び、戻り先を ra に上書き保存する
    jal ra, add_func

    # 戻ってきた後の処理
    addi a0, a0, 5       # a0 = 30 + 5 = 35

    # --- エピローグ (fpの解体) ---
    # 【変更点】spではなく、絶対に動かない fp を基準に復元する！
    ld ra, -8(fp)        # fpのすぐ下にある ra を復元 (8(sp)と同じ場所)
    ld fp, -16(fp)       # さらにその下にある 古いfp を復元 (0(sp)と同じ場所)

    addi sp, sp, 16      # スタックを片付ける (spをfpと同じ高さに戻す)

    # 呼び出し元へ帰還
    jalr zero, 0(ra)


# ==========================================
# 3. 葉関数 (add_func)
# ==========================================
add_func:
    # 葉関数(Leaf Function)なので、他の関数を呼ばない＝raもfpも壊れない。
    # したがってスタックフレームの構築すら省略できる究極の最適化状態！
    add a0, a0, a1     
    
    # 呼び出し元へ帰還
    jalr zero, 0(ra)
